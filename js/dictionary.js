export function canFormWordFromWheel(word, wheelLetters) {
    const counts = {};
    for (let char of wheelLetters) {
        counts[char] = (counts[char] || 0) + 1;
    }
    for (let char of word) {
        if (!counts[char]) return false;
        counts[char]--;
    }
    return true;
}

export function filterRedundantPlurals(words) {
    const wordSet = new Set(words);
    return words.filter(w => {
        if (w.length >= 3 && wordSet.has(w + 'S')) return false;
        return true;
    });
}

export function getTierInfoForLevel(lvl) {
    if (lvl <= 10) {
        // Beginner: 5-letter wheel, minimum 5 words on board!
        return { tierKey: 'tier_beginner', name: 'BEGINNER', css: 'diff-easy', minTarget: 5, maxGrid: 6 };
    } else if (lvl <= 30) {
        // Explorer: 5-6 letter wheel, 5-6 words on board
        return { tierKey: 'tier_explorer', name: 'EXPLORER', css: 'diff-medium', minTarget: 5, maxGrid: 7 };
    } else if (lvl <= 60) {
        // Challenger: 6-letter wheel, 6-7 words on board
        return { tierKey: 'tier_challenger', name: 'CHALLENGER', css: 'diff-hard', minTarget: 6, maxGrid: 7 };
    } else {
        // Master: 7-letter wheel, 7-8 words on board
        return { tierKey: 'tier_master', name: 'MASTER', css: 'diff-hardest', minTarget: 7, maxGrid: 8 };
    }
}
